"""Build the RC-1 fixed evaluation case set (>=60 cases).

Output: eval/rc1_cases.json

Design:
- Every case is independent: its own synthetic user input, authorized fact
  package, expected boundaries and machine-check hints.
- Facts carry stable fact_ids and source_ids. The runner must record whether
  the model cited them; invented fact_ids are counted as citation errors.
- The case file is *not* a test oracle for natural language. Auto checks are
  triage aids; every case also has a human review record in the run artifact.
- Expected boundaries are deliberately NOT shown to the model. The model sees
  only the specialist role, the authorized facts and the user input.
"""
from __future__ import annotations

import json
from pathlib import Path

OUT = Path(__file__).resolve().parent / "rc1_cases.json"


def F(fid: str, metric: str, value, unit: str = "", status: str = "observed",
      sources: list[str] | None = None, calc: str = "", **extra) -> dict:
    fact = {
        "fact_id": fid,
        "metric": metric,
        "value": value,
        "unit": unit,
        "status": status,
        "source_ids": sources or [],
        "calculation": calc,
    }
    fact.update(extra)
    return fact


def T(name: str, summary: str) -> dict:
    return {"name": name, "output_summary": summary}


def C(case_id: str, group: str, specialist: str, risk: str, user_input: str,
      facts: list[dict], tools: list[dict], boundaries: list[str],
      required: list[str], required_any: list[str],
      forbidden: list[str] | None = None, scenario: str | None = None,
      seed: dict | None = None, notes: str = "") -> dict:
    case = {
        "case_id": case_id,
        "group": group,
        "specialist": specialist,
        "risk": risk,
        "input": user_input,
        "authorized_facts": facts,
        "tools": tools,
        "expected_boundaries": boundaries,
        "required_fact_ids": required,
        "required_any": required_any,
        "forbidden_patterns": forbidden or [],
        "notes": notes,
    }
    if scenario:
        case["scenario"] = scenario
    if seed:
        case["seed"] = seed
    return case


